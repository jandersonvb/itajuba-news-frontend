import type { Metadata } from 'next';
import { siteUrl } from './api';

export const SITE_NAME = 'Itajubá News';
export const SITE_DESCRIPTION = 'Notícias de Itajubá e do Sul de Minas. Informação que conecta você.';

/*
 * Next.js does not merge metadata objects between the layout and the page: a page that sets
 * `openGraph` or `alternates` replaces the layout's whole object. Pages that set them start from
 * the values below, so they keep the site name, the default image and the RSS link.
 */

/** `openGraph` fields shared by every page. */
export const OPEN_GRAPH = { siteName: SITE_NAME, locale: 'pt_BR' } as const;

/** Default share image, generated by src/app/opengraph-image.tsx. */
export const DEFAULT_OG_IMAGE = {
  url: '/opengraph-image',
  type: 'image/png',
  width: 1200,
  height: 630,
  alt: 'Itajubá News: notícias de Itajubá e do Sul de Minas',
};

/** RSS feed, announced in the `<head>` of every page. */
export const FEED_TYPES = { 'application/rss+xml': '/feed.xml' };

/** `alternates` of a page: its canonical URL, plus the RSS link. */
export const alternates = (canonical: string): Metadata['alternates'] => ({ canonical, types: FEED_TYPES });

/** The portal as publisher, for the JSON-LD of the home and of the articles. */
export const publisherLd = () => ({
  '@type': 'NewsMediaOrganization',
  name: SITE_NAME,
  url: siteUrl(),
  logo: { '@type': 'ImageObject', url: siteUrl() + '/logo.png', width: 225, height: 225 },
});
